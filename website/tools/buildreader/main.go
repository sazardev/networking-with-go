// cardURLFor returns the most specific branded social card that exists on
// disk for a page. Precedence: a per-chapter card (og-<part>-<chapter>.png,
// generated by website/tools/gencards/gencards.py), then a per-part card
// (og-<part>.png), then the generic landing card (og-card.png). The special
// slugs "read" and "topics" resolve to og-read.png / og-topics.png.
func cardURLFor(partSlug string, chapterSlug ...string) string {
	name := partSlug
	if len(chapterSlug) > 0 && chapterSlug[0] != "" {
		name = partSlug + "-" + chapterSlug[0]
	}
	if _, err := os.Stat("website/assets/og-" + name + ".png"); err == nil {
		return siteBase + "/assets/og-" + name + ".png"
	}
	return ogCardURL
}

